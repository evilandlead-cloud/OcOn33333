  function hash(text) {
    let n = 2166136261;
    for (const c of String(text)) { n ^= c.charCodeAt(0); n = Math.imul(n, 16777619); }
    return n >>> 0;
  }
  const normalize = text => String(text || '').toLowerCase().replace(/[\s\p{P}\p{S}]/gu, '');
  const number = n => typeof n === 'number' && Number.isFinite(n) && n >= 0 ? n : 0;
  function evidence(items, category, platform) {
    let measured = 0, views = 0, engagement = 0, leads = 0;
    for (const item of items.filter(i => i && i.category === category)) {
      const metrics = item.metrics && typeof item.metrics === 'object' ? item.metrics : {};
      let itemViews = 0;
      for (const [name, m] of Object.entries(metrics)) {
        if (!m || typeof m !== 'object' || (platform !== '全部' && name !== platform)) continue;
        const v = number(m.views);
        if (!v) continue;
        itemViews += v;
        views += v;
        leads += number(m.leads);
        engagement += ['likes', 'comments', 'saves', 'shares'].reduce((n, k) => n + number(m[k]), 0);
      }
      if (itemViews) measured++;
    }
    if (!views) return {score: 0, reason: '待验证：该栏目在当前平台范围内还没有可用曝光样本。先小规模发布，再用互动与有效咨询复盘。'};
    const interactionRate = engagement / views, leadRate = leads / views * 1000;
    const confidence = views / (views + 1000) * measured / (measured + 2);
    return {
      score: (Math.min(interactionRate, 1) * 100 + Math.min(leadRate, 100) * 2) * confidence,
      reason: `本地参考：${measured} 条已录入曝光的内容，累计 ${views.toLocaleString('zh-CN')} 次曝光，互动率 ${(interactionRate * 100).toFixed(2)}%，每千次曝光有效咨询 ${leadRate.toFixed(2)}。按栏目表现提供参考，小样本不代表未来效果。`
    };
  }
  const catalog = categories.flatMap((category, ci) => subjects[category].flatMap((subject, si) => angles[category].map((make, ai) => ({
    ...make(subject), id: `hdw-${ci + 1}-${si + 1}-${ai + 1}`, category,
    verification: subject[3], keywords: `${category} ${subject.join(' ')} 花地湾 古玩城 广州 白鹅潭`,
    preferredPlatform: ci < 2 ? '视频号' : '小红书'
  }))));

  function adapt(topic, selectedPlatform) {
    const platform = platforms.includes(selectedPlatform) ? selectedPlatform : topic.preferredPlatform;
    const guidance = {
      抖音: '建议 20—45 秒短视频：前 3 秒提出具体问题，画面先于解释。',
      视频号: '建议 45—90 秒视频：保留人物原声与器物细节，结尾给出到访或交流理由。',
      小红书: '建议 6—9 张图文：封面一个明确问题，后续分图给细节、清单与实际信息。'
    }[platform];
    const {keywords, preferredPlatform, ...result} = topic;
    return {...result, platform, kind: platform === '小红书' ? '图文' : '视频', hook: topic.hook, formatGuidance: guidance};
  }

  function generate(options = {}) {
    const category = options.category || '全部';
    const platform = platforms.includes(options.platform) ? options.platform : '全部';
    const count = Math.max(1, Math.min(24, Math.floor(Number(options.count) || 6)));
    const seed = Number.isFinite(Number(options.seed)) ? Number(options.seed) : 0;
    const items = Array.isArray(options.items) ? options.items : [];
    const seen = new Set(Array.isArray(options.seen) ? options.seen : []);
    const plannedTitles = new Set(items.map(x => normalize(x && x.title)));
    const tokens = String(options.keyword || '').trim().toLowerCase().split(/[\s,，、]+/).filter(Boolean);
    const pool = catalog.filter(t => (category === '全部' || category === t.category)
      && !plannedTitles.has(normalize(t.title))
      && tokens.every(token => `${t.title} ${t.keywords} ${t.hook} ${t.shots.join(' ')}`.toLowerCase().includes(token)));
    const remainingPool = pool.filter(t => !seen.has(t.id));
    const stats = Object.fromEntries(categories.map(c => [c, evidence(items, c, platform)]));
    // Round-robin gives broad coverage. Evidence orders categories, not promises of virality.
    const order = categories.filter(c => remainingPool.some(t => t.category === c)).sort((a, b) =>
      stats[b].score - stats[a].score || hash(`${seed}:${a}`) - hash(`${seed}:${b}`));
    const buckets = Object.fromEntries(order.map(c => [c, remainingPool.filter(t => t.category === c).sort((a, b) =>
      hash(`${seed}:${a.id}`) - hash(`${seed}:${b.id}`) || a.id.localeCompare(b.id))]));
    const selected = [];
    while (selected.length < count && order.some(c => buckets[c].length)) {
      for (const c of order) {
        if (selected.length >= count) break;
        if (buckets[c].length) selected.push(buckets[c].shift());
      }
    }
    return {
      topics: selected.map(t => ({...adapt(t, platform), reason: stats[t.category].reason})),
      remaining: Math.max(0, remainingPool.length - selected.length),
      total: pool.length
    };
  }

  global.TopicEngine = Object.freeze({generate, categories: categories.slice(), platforms: platforms.slice(), size: catalog.length});
